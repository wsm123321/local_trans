def _set_gate_metrics(d: Path, rank_gain: float, value_extra: float = 0.0, dual_extra: float = 0.0) -> None:
    """Make a compact deterministic Geometry/Rank/Value fixture in raw results."""
    p = d / "results.csv"
    frame = pd.read_csv(p)
    positive = frame["relation_or_control"].isin(analyzer.POSITIVE_RELATIONS)
    permuted = frame["relation_or_control"].eq("identity_label_permutation")
    negative = frame["relation_or_control"].isin(analyzer.NEGATIVE_RELATIONS)
    for metric in analyzer.DECISION_METRICS:
        # Higher is better for the first two metrics.  Regret is lower better,
        # so reducing it by the same amount yields the same oriented delta.
        base = 0.5
        frame.loc[:, metric] = base
        gain = rank_gain
        rank = frame.method.eq("Oracle-Rank+Residual")
        value = frame.method.eq("Oracle-Value+Residual")
        dual = frame.method.eq("Oracle-Rank+Value+Residual")
        frame.loc[positive & rank, metric] = base + gain
        frame.loc[positive & value, metric] = base + gain + value_extra
        frame.loc[positive & dual, metric] = base + gain + dual_extra
        # Identity/permutation is the negative control for the identity rule.
        frame.loc[permuted & (rank | value | dual), metric] = base
        # Do not let negative conditions look like positive transfer.
        frame.loc[negative & (rank | value | dual), metric] = base - rank_gain
        if metric == "normalized_top1_regret":
            # Convert the values above into lower-is-better regret values while
            # retaining the desired oriented deltas.
            frame.loc[positive & rank, metric] = base - gain
            frame.loc[positive & value, metric] = base - gain - value_extra
            frame.loc[positive & dual, metric] = base - gain - dual_extra
            frame.loc[permuted & (rank | value | dual), metric] = base
            frame.loc[negative & (rank | value | dual), metric] = base + rank_gain
    frame.to_csv(p, index=False)


def _decision_from_mutated_fixture(tmp_path: Path, rank_gain: float, value_extra: float = 0.0, dual_extra: float = 0.0) -> dict:
    d = _fixture(tmp_path)
