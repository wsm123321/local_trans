def test_negative_controls_decide_per_condition_not_pooled(tmp_path: Path) -> None:
    d = _fixture(tmp_path)
    frame = pd.read_csv(d / "results.csv")
    # Make one metric positive in each of three distinct conditions. Pooling
    # these rows would falsely replicate two metrics, but no condition reaches
    # the required 2/3 metric threshold.
    for metric, condition in zip(analyzer.DECISION_METRICS, analyzer.NEGATIVE_RELATIONS):
        mask = frame.relation_or_control.eq(condition) & frame.method.eq("Oracle-Rank+Residual")
        frame.loc[mask, metric] += .2 if metric != "normalized_top1_regret" else -.2
    frame.to_csv(d / "results.csv", index=False)
    results = analyzer._normalise_results(frame)
    decision = analyzer.decide(results, analyzer._contrasts(results))[1]
    ev = decision["head_evaluations"]["rank"]
    assert ev["negative_conditions_replicating"] == 0
    assert ev["negative_rule_pass"]
    assert all(detail["metrics_replicating"] == 1 for detail in ev["negative_condition_detail"].values())


